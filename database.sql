CREATE DATABASE IF NOT EXISTS checkpoints_trekking CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

USE checkpoints_trekking;

SET FOREIGN_KEY_CHECKS=0;

DROP TABLE IF EXISTS passagem;

DROP TABLE IF EXISTS participacao;

DROP TABLE IF EXISTS checkpoint;

DROP TABLE IF EXISTS equipe;

DROP TABLE IF EXISTS corrida;

DROP TABLE IF EXISTS professor;

SET FOREIGN_KEY_CHECKS=1;

CREATE TABLE corrida (id_corrida INT AUTO_INCREMENT PRIMARY KEY, nome VARCHAR(120) NOT NULL UNIQUE, CHECK (CHAR_LENGTH(TRIM(nome))>0)) ENGINE=InnoDB;

CREATE TABLE equipe (id_equipe INT AUTO_INCREMENT PRIMARY KEY, nome VARCHAR(120) NOT NULL UNIQUE, CHECK (CHAR_LENGTH(TRIM(nome))>0)) ENGINE=InnoDB;

CREATE TABLE professor (id_professor INT AUTO_INCREMENT PRIMARY KEY, nome VARCHAR(120) NOT NULL UNIQUE, CHECK (CHAR_LENGTH(TRIM(nome))>0)) ENGINE=InnoDB;

CREATE TABLE checkpoint (id_checkpoint INT AUTO_INCREMENT PRIMARY KEY, numero INT NOT NULL CHECK(numero>0), id_corrida INT NOT NULL, id_professor INT NOT NULL, UNIQUE(id_corrida,numero), UNIQUE(id_checkpoint,id_corrida,id_professor), FOREIGN KEY(id_corrida) REFERENCES corrida(id_corrida) ON DELETE RESTRICT ON UPDATE CASCADE, FOREIGN KEY(id_professor) REFERENCES professor(id_professor) ON DELETE RESTRICT ON UPDATE CASCADE) ENGINE=InnoDB;

CREATE TABLE participacao (id_corrida INT NOT NULL, id_equipe INT NOT NULL, PRIMARY KEY(id_corrida,id_equipe), FOREIGN KEY(id_corrida) REFERENCES corrida(id_corrida) ON DELETE RESTRICT ON UPDATE CASCADE, FOREIGN KEY(id_equipe) REFERENCES equipe(id_equipe) ON DELETE RESTRICT ON UPDATE CASCADE) ENGINE=InnoDB;

CREATE TABLE passagem (id_passagem INT AUTO_INCREMENT PRIMARY KEY, id_corrida INT NOT NULL, id_equipe INT NOT NULL, id_checkpoint INT NOT NULL, id_professor INT NOT NULL, momento DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, UNIQUE(id_corrida,id_equipe,id_checkpoint), FOREIGN KEY(id_corrida,id_equipe) REFERENCES participacao(id_corrida,id_equipe) ON DELETE RESTRICT ON UPDATE CASCADE, FOREIGN KEY(id_checkpoint,id_corrida,id_professor) REFERENCES checkpoint(id_checkpoint,id_corrida,id_professor) ON DELETE RESTRICT ON UPDATE CASCADE) ENGINE=InnoDB;

